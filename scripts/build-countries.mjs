// Regenerates src/countries.ts from mledoze/countries (MIT). Run it if the menu ever needs to change.
// The menu is the 194 UN member states. Jev picks one of these and nothing else.
import { writeFileSync } from "node:fs";

const SOURCE = "https://raw.githubusercontent.com/mledoze/countries/master/countries.json";

const raw = await (await fetch(SOURCE)).json();

const countries = raw
  .filter((c) => c.independent && c.unMember && Array.isArray(c.latlng))
  .map((c) => ({
    code: c.cca2,
    name: c.name.common,
    lat: Number(c.latlng[0].toFixed(3)),
    lng: Number(c.latlng[1].toFixed(3)),
    region: c.subregion || c.region,
  }))
  .sort((a, b) => a.name.localeCompare(b.name));

const lines = countries.map((c) =>
  `  { code: "${c.code}", name: ${JSON.stringify(c.name)}, lat: ${c.lat}, lng: ${c.lng}, region: ${JSON.stringify(c.region)} },`);

writeFileSync(new URL("../src/countries.ts", import.meta.url), `// Generated by scripts/build-countries.mjs from mledoze/countries (MIT). Do not edit by hand.
// The menu Jev chooses from: every UN member state, with the centroid used to score its guess.

export type Country = { code: string; name: string; lat: number; lng: number; region: string };

export const COUNTRIES: readonly Country[] = [
${lines.join("\n")}
];

const byCode = new Map(COUNTRIES.map((c) => [c.code, c]));

export const countryByCode = (code: string): Country | undefined => byCode.get(code);
`, "utf8");

console.log(`wrote ${countries.length} countries`);
